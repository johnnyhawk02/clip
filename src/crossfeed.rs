/// The crossfeed filters at one output rate, and the recent input they run over.
pub struct Crossfeed {
    direct: Vec<f32>,
    cross: Vec<f32>,
    left: Vec<f32>,
    right: Vec<f32>,
    pos: usize,
}

impl Crossfeed {
    pub fn new(rate: f64) -> Crossfeed {
        let (direct, cross) = (resample(&DIRECT, rate), resample(&CROSS, rate));
        let n = direct.len();
        Crossfeed { direct, cross, left: vec![0.0; n], right: vec![0.0; n], pos: 0 }
    }

    /// One stereo frame in, one out.
    pub fn process(&mut self, l: f32, r: f32) -> (f32, f32) {
        let n = self.direct.len();
        self.pos = (self.pos + 1) % n;
        self.left[self.pos] = l;
        self.right[self.pos] = r;
        let (mut ol, mut or) = (0.0, 0.0);
        for k in 0..n {
            let i = (self.pos + n - k) % n;
            let (xl, xr) = (self.left[i], self.right[i]);
            ol += self.direct[k] * xl + self.cross[k] * xr;
            or += self.direct[k] * xr + self.cross[k] * xl;
        }
        (ol, or)
    }

    /// Forget the past (after a stop, so the next start doesn't carry an old tail).
    pub fn reset(&mut self) {
        self.left.fill(0.0);
        self.right.fill(0.0);
    }
}

/// A filter measured at `RATE`, redrawn at `rate` by band-limited (windowed sinc) interpolation,
/// keeping its gain. It starts `HALF` samples early so the ringing before the first tap isn't
/// cut off (both filters shift together, so only the playback latency grows, by under 1 ms).
fn resample(h: &[f32], rate: f64) -> Vec<f32> {
    if (rate - RATE).abs() < 0.5 {
        return h.to_vec();
    }
    let ratio = RATE / rate;
    let cut = (1.0 / ratio).min(1.0);
    const HALF: f64 = 16.0;
    let pre = (HALF / cut / ratio).ceil() as usize;
    let m = (h.len() as f64 / ratio).ceil() as usize + pre;
    (0..m)
        .map(|j| {
            let t = (j as f64 - pre as f64) * ratio;
            let lo = (t - HALF / cut).floor().max(0.0) as usize;
            let hi = ((t + HALF / cut).ceil().max(0.0) as usize).min(h.len() - 1);
            let mut acc = 0.0;
            for (k, &v) in h.iter().enumerate().take(hi + 1).skip(lo) {
                let x = (t - k as f64) * cut;
                let sinc = if x.abs() < 1e-9 { 1.0 } else { (std::f64::consts::PI * x).sin() / (std::f64::consts::PI * x) };
                let w = 0.5 + 0.5 * (std::f64::consts::PI * x / HALF).cos();
                if x.abs() < HALF {
                    acc += v as f64 * sinc * w * cut;
                }
            }
            (acc * ratio) as f32
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keeps_its_gain_at_other_rates() {
        let sum = |h: &[f32]| h.iter().sum::<f32>();
        for rate in [48000.0, 88200.0, 96000.0] {
            let c = Crossfeed::new(rate);
            assert!((sum(&c.direct) - sum(&DIRECT)).abs() < 0.01, "{rate}: {} vs {}", sum(&c.direct), sum(&DIRECT));
            assert!((sum(&c.cross) - sum(&CROSS)).abs() < 0.01, "{rate}");
        }
    }

    #[test]
    fn a_click_on_the_left_reaches_both_ears() {
        let mut c = Crossfeed::new(RATE);
        let (l, r) = c.process(1.0, 0.0);
        assert_eq!((l, r), (DIRECT[0], CROSS[0]));
    }
}
